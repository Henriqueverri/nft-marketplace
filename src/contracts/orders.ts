import { z } from 'zod'
import { emailSchema } from './auth'
import { appliedCouponSchema, cartItemIdSchema, quoteSchema } from './cart'
import { networkIdSchema, nftIdSchema, nftImageKeySchema } from './catalog'
import { ethAmountSchema, isoDateTimeSchema } from './common'
import { walletProviderSchema, walletSchema } from './wallets'

/**
 * Order contracts. Orders are private: every route needs a session, and the owner
 * comes from the token, never from the request.
 *
 * POST /api/orders            → 201 Order (new) | 200 Order (same key and payload again)
 *                               header Idempotency-Key (required)
 * GET  /api/orders/:orderId   → 200 Order | 403 (another user's) | 404
 * GET  /api/orders            → 200 OrderList (the user's own, newest first)
 *                               ?status=pending|confirmed|rejected  ?idempotencyKey=<key>
 *
 * The listing lets the client find, without creating anything, the pending orders
 * to follow after the app opens and the order of an attempt whose answer was lost.
 *
 * An order is created `pending` from a quote the server issued to the same user.
 * The payment then settles it once, as `confirmed` or `rejected`; both are terminal.
 * The receipt is a snapshot taken at creation and never recomputed from the catalog.
 */

export const IDEMPOTENCY_KEY_HEADER = 'Idempotency-Key'

/** One key per purchase attempt, generated by the client (a UUID fits). */
export const idempotencyKeySchema = z.string().regex(/^[A-Za-z0-9_-]{16,128}$/, 'Chave de idempotência inválida.')

export const orderIdSchema = z.string().regex(/^ord_[a-z0-9]+$/)

export const quoteIdSchema = quoteSchema.shape.quoteId

/** A quote can back an order for this long after it was issued. */
export const QUOTE_TTL_MS = 10 * 60 * 1000

/** Collector data of the payment form. */
export const buyerSchema = z.object({
  fullName: z
    .string({ error: 'Informe seu nome completo.' })
    .trim()
    .min(3, 'Informe seu nome completo.')
    .max(80, 'O nome deve ter no máximo 80 caracteres.'),
  email: emailSchema,
})
export type Buyer = z.infer<typeof buyerSchema>

/**
 * What the user confirmed: the quote on screen (id and cart revision), the wallet and
 * the network. Prices are never sent; the server takes them from its own quote.
 */
export const createOrderRequestSchema = z.object({
  quoteId: quoteIdSchema,
  cartRevision: z.number().int().nonnegative(),
  walletId: walletSchema.shape.id,
  networkId: networkIdSchema,
  buyer: buyerSchema,
})
export type CreateOrderRequest = z.infer<typeof createOrderRequestSchema>
export type CreateOrderRequestInput = z.input<typeof createOrderRequestSchema>

export const orderStatusSchema = z.enum(['pending', 'confirmed', 'rejected'])
export type OrderStatus = z.infer<typeof orderStatusSchema>

export const orderRejectionReasonSchema = z.enum(['payment-declined', 'out-of-stock'])
export type OrderRejectionReason = z.infer<typeof orderRejectionReasonSchema>

export const receiptLineSchema = z.object({
  itemId: cartItemIdSchema,
  nftId: nftIdSchema,
  nftName: z.string(),
  tokenId: z.string(),
  imageKey: nftImageKeySchema,
  editionName: z.string(),
  quantity: z.number().int().positive(),
  unitPriceEth: ethAmountSchema,
  lineTotalEth: ethAmountSchema,
})
export type ReceiptLine = z.infer<typeof receiptLineSchema>

/** Everything the receipt shows, frozen when the order was created. */
export const receiptSchema = z.object({
  lines: z.array(receiptLineSchema).min(1),
  itemCount: z.number().int().positive(),
  subtotalEth: ethAmountSchema,
  discountEth: ethAmountSchema,
  networkFeeEth: ethAmountSchema,
  totalEth: ethAmountSchema,
  coupon: appliedCouponSchema.nullable(),
  buyer: buyerSchema,
  wallet: z.object({
    id: walletSchema.shape.id,
    nickname: z.string(),
    address: walletSchema.shape.address,
    provider: walletProviderSchema,
  }),
  network: z.object({ id: networkIdSchema, name: z.string(), currency: z.string() }),
  /** Simulated references: no real chain is involved. */
  transactionHash: z.string().regex(/^0x[0-9a-f]{64}$/),
  explorerUrl: z.url(),
})
export type Receipt = z.infer<typeof receiptSchema>

export const orderSchema = z.object({
  orderId: orderIdSchema,
  status: orderStatusSchema,
  /** 1 when created, 2 after it settled; grows on every transition (order.updated carries it). */
  version: z.number().int().positive(),
  quoteId: quoteIdSchema,
  createdAt: isoDateTimeSchema,
  /** When it became confirmed or rejected; null while pending. */
  settledAt: isoDateTimeSchema.nullable(),
  rejection: z.object({ reason: orderRejectionReasonSchema, message: z.string() }).nullable(),
  receipt: receiptSchema,
})
export type Order = z.infer<typeof orderSchema>

/** Most recent orders first; at most `ORDER_LIST_LIMIT`. */
export const ORDER_LIST_LIMIT = 20
export const orderListQuerySchema = z.object({
  status: orderStatusSchema.optional(),
  idempotencyKey: idempotencyKeySchema.optional(),
})
export type OrderListQuery = z.infer<typeof orderListQuerySchema>
export const orderListSchema = z.object({ orders: z.array(orderSchema) })
export type OrderList = z.infer<typeof orderListSchema>

/* ---------- 409 QUOTE_STALE ---------- */

export const quoteStaleReasonSchema = z.enum([
  /** Unknown to the server for this user (never issued, evicted or another user's). */
  'quote-not-found',
  'quote-expired',
  /** Already used by another order (a different Idempotency-Key). */
  'quote-used',
  /** The cart moved past the quoted revision (user, another tab or the catalog). */
  'cart-changed',
])
export type QuoteStaleReason = z.infer<typeof quoteStaleReasonSchema>

export const quoteChangeSchema = z.discriminatedUnion('kind', [
  z.object({
    kind: z.literal('price-changed'),
    itemId: cartItemIdSchema,
    nftId: nftIdSchema,
    label: z.string(),
    previousUnitPriceEth: ethAmountSchema,
    currentUnitPriceEth: ethAmountSchema,
  }),
  z.object({
    kind: z.literal('quantity-changed'),
    itemId: cartItemIdSchema,
    nftId: nftIdSchema,
    label: z.string(),
    previousQuantity: z.number().int().positive(),
    currentQuantity: z.number().int().positive(),
  }),
  z.object({
    kind: z.literal('item-removed'),
    itemId: cartItemIdSchema,
    nftId: nftIdSchema,
    label: z.string(),
    previousQuantity: z.number().int().positive(),
  }),
  z.object({
    kind: z.literal('item-added'),
    itemId: cartItemIdSchema,
    nftId: nftIdSchema,
    label: z.string(),
    currentQuantity: z.number().int().positive(),
  }),
  z.object({
    kind: z.literal('coupon-changed'),
    previousCode: z.string().nullable(),
    currentCode: z.string().nullable(),
  }),
])
export type QuoteChange = z.infer<typeof quoteChangeSchema>

/**
 * `error.details` of a 409 QUOTE_STALE: why, what changed line by line, and a fresh
 * quote of the cart as it is now (null if the cart is empty), so the client can show
 * the new values and ask the user to confirm again. Nothing was ordered or consumed.
 */
export const quoteStaleDetailsSchema = z.object({
  reasons: z.array(quoteStaleReasonSchema).min(1),
  changes: z.array(quoteChangeSchema),
  previousTotalEth: ethAmountSchema.nullable(),
  quote: quoteSchema.nullable(),
  /** With `quote-used`: the order that used it. */
  orderId: orderIdSchema.nullable(),
})
export type QuoteStaleDetails = z.infer<typeof quoteStaleDetailsSchema>
