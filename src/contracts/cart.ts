import { z } from 'zod'
import { editionSchema, nftIdSchema, nftImageKeySchema } from './catalog'
import { ethAmountSchema, isoDateTimeSchema } from './common'

/**
 * Cart and quote contracts. The cart lives on the (mock) server: the session user's
 * cart, or a visitor cart identified by the `X-Cart-Id` header. Prices, limits and
 * totals are always computed by the server; the client only renders them.
 *
 * GET    /api/cart                     → Cart
 * POST   /api/cart/items               → Cart   (AddCartItemRequest; adds to an existing line)
 * PATCH  /api/cart/items/:itemId       → Cart   (UpdateCartItemRequest; sets the quantity)
 * DELETE /api/cart/items/:itemId       → Cart
 * PUT    /api/cart/coupon              → Cart   (ApplyCouponRequest)
 * DELETE /api/cart/coupon              → Cart
 * DELETE /api/cart/notices             → Cart   (the user read the adjustment notices)
 * POST   /api/cart/merge               → Cart   (session + X-Cart-Id: visitor cart into the account)
 * POST   /api/quotes                   → Quote  (QuoteRequest)
 */

export const CART_ID_HEADER = 'X-Cart-Id'

/** Visitor cart id: generated by the client (random UUID), opaque to the server. */
export const guestCartIdSchema = z.string().regex(/^gc_[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/)

/** A line is one edition of one NFT; its id is the edition id. */
export const cartItemIdSchema = editionSchema.shape.id

export const MAX_CART_LINES = 20
export const MAX_LINE_QUANTITY = 99

export const quantitySchema = z
  .number({ error: 'Informe a quantidade.' })
  .int('A quantidade deve ser um número inteiro.')
  .min(1, 'A quantidade mínima é 1.')
  .max(MAX_LINE_QUANTITY, `A quantidade máxima é ${MAX_LINE_QUANTITY}.`)

export const cartItemSchema = z.object({
  id: cartItemIdSchema,
  nft: z.object({
    id: nftIdSchema,
    name: z.string(),
    tokenId: z.string(),
    imageKey: nftImageKeySchema,
    /** Version of the NFT the line was priced with (nft.updated carries newer ones). */
    version: z.number().int().positive(),
  }),
  edition: z.object({ id: cartItemIdSchema, name: z.string() }),
  quantity: z.number().int().positive(),
  /** Current price of one edition (the server keeps it in step with the catalog). */
  unitPriceEth: ethAmountSchema,
  /** min(maxPerOrder, available): the most this line can hold right now. */
  maxQuantity: z.number().int().nonnegative(),
})
export type CartItem = z.infer<typeof cartItemSchema>

export const cartNoticeKindSchema = z.enum(['price-changed', 'quantity-reduced', 'removed', 'merged', 'coupon-removed'])
export type CartNoticeKind = z.infer<typeof cartNoticeKindSchema>

/**
 * A change the server made to the cart on its own (stock, price, merge, expired
 * coupon). Kept until the user dismisses it, so a refresh does not lose it.
 */
export const cartNoticeSchema = z.object({
  id: z.string(),
  kind: cartNoticeKindSchema,
  message: z.string(),
  nftId: nftIdSchema.nullable(),
  createdAt: isoDateTimeSchema,
})
export type CartNotice = z.infer<typeof cartNoticeSchema>

export const appliedCouponSchema = z.object({ code: z.string(), percentOff: z.number().int().min(1).max(100) })
export type AppliedCoupon = z.infer<typeof appliedCouponSchema>

export const cartSchema = z.object({
  owner: z.enum(['guest', 'user']),
  /** Grows on every change (by the user or by the server); a quote is bound to it. */
  revision: z.number().int().nonnegative(),
  items: z.array(cartItemSchema),
  /** Sum of the quantities (the header badge). */
  itemCount: z.number().int().nonnegative(),
  coupon: appliedCouponSchema.nullable(),
  notices: z.array(cartNoticeSchema),
})
export type Cart = z.infer<typeof cartSchema>

export const addCartItemRequestSchema = z.object({
  nftId: nftIdSchema,
  editionId: cartItemIdSchema,
  quantity: quantitySchema,
})
export type AddCartItemRequest = z.infer<typeof addCartItemRequestSchema>

export const updateCartItemRequestSchema = z.object({ quantity: quantitySchema })
export type UpdateCartItemRequest = z.infer<typeof updateCartItemRequestSchema>

export const couponCodeSchema = z
  .string({ error: 'Digite o código promocional.' })
  .trim()
  .min(1, 'Digite o código promocional.')
  .max(32, 'Código promocional inválido.')
  .transform((code) => code.toUpperCase())

export const applyCouponRequestSchema = z.object({ code: couponCodeSchema })
export type ApplyCouponRequest = z.input<typeof applyCouponRequestSchema>

/* ---------- Quote: POST /api/quotes ---------- */

/** Estimated network fee of one order (Figma "Taxa de rede", "Taxa estimada"). */
export const ESTIMATED_NETWORK_FEE_ETH = '0.016'

/**
 * The client quotes the cart revision it is showing. If the server's cart moved on
 * (another tab, a price or stock change), it answers 409 CART_CHANGED instead of a
 * quote for items the user is not looking at.
 */
export const quoteRequestSchema = z.object({ cartRevision: z.number().int().nonnegative() })
export type QuoteRequest = z.infer<typeof quoteRequestSchema>

export const quoteLineSchema = z.object({
  itemId: cartItemIdSchema,
  nftId: nftIdSchema,
  quantity: z.number().int().positive(),
  unitPriceEth: ethAmountSchema,
  lineTotalEth: ethAmountSchema,
})
export type QuoteLine = z.infer<typeof quoteLineSchema>

/**
 * Financial summary of a cart revision. All amounts are exact decimal strings:
 * subtotal = Σ unit × quantity; discount = subtotal × percent / 100, rounded down to
 * the wei; total = subtotal − discount + network fee.
 */
export const quoteSchema = z.object({
  quoteId: z.string().regex(/^qt_[a-z0-9-]+$/),
  cartRevision: z.number().int().nonnegative(),
  lines: z.array(quoteLineSchema),
  itemCount: z.number().int().nonnegative(),
  subtotalEth: ethAmountSchema,
  discountEth: ethAmountSchema,
  networkFeeEth: ethAmountSchema,
  totalEth: ethAmountSchema,
  coupon: appliedCouponSchema.nullable(),
  /** NFT versions the prices came from; a newer `nft.updated` makes the quote stale. */
  nftVersions: z.record(nftIdSchema, z.number().int().positive()),
  createdAt: isoDateTimeSchema,
})
export type Quote = z.infer<typeof quoteSchema>
